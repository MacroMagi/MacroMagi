"""Generates docs/NODES.md from the app's own node definitions.

The block reference is produced from the same data the editor uses, so it
cannot drift from what the app actually offers. Run it after changing or
adding a node definition:

    cargo run -p magi-app -- nodes | python tools/node_docs.py > docs/NODES.md
"""

import io
import json
import sys

CATEGORIES = [
    ("flow", "Flow", "Where a macro starts, waits, loops, branches and stops, and the pieces it is built from."),
    ("input", "Input", "Sending keyboard and mouse input."),
    ("vision", "Vision", "Looking at the screen. These are value blocks: they have no place in the "
     "order of execution and are evaluated whenever another block reads them."),
    ("sound", "Sound", "Listening to what the computer plays, or to the microphone. Value blocks, like "
     "the vision blocks."),
    ("ai", "AI", "Small vision models prepared in the Magic tab, run on what is on screen."),
    ("window", "Window", "Working with program windows."),
    ("variables", "Variables", "Named values a macro reads and changes while it runs. Any setting of any "
     "block can also follow a variable (the link button next to it)."),
    ("logic", "Logic", "Combining and producing values: true/false, numbers and text."),
    ("system", "System", "The clipboard and notifications."),
    ("script", "Script", "Your own code as a step of the macro."),
    ("notes", "Notes", "Explanations on the canvas. They never run."),
    ("addon", "Add-ons", "Blocks contributed by add-ons."),
]

TYPE_NAMES = {"bool": "true/false", "number": "number", "point": "screen position", "text": "text", "any": "any value"}

KIND_NAMES = {
    "bool": "on/off", "int": "whole number", "float": "number", "duration": "duration",
    "percent": "percentage", "text": "text", "code": "code", "choice": "choice", "key": "key",
    "mouse_button": "mouse button", "hotkey": "hotkey", "point": "screen position",
    "region": "screen area", "color": "colour", "image": "image", "recording": "recording",
    "actions": "list of inputs", "cases": "list of cases", "clicker": "Auto Clicker settings",
    "variable": "variable", "definition": "definition", "block": "block", "display": "display",
    "audio": "sound", "images": "list of images", "sounds": "list of sounds",
    "audio_device": "microphone", "model": "AI model", "model_settings": "model settings",
}


def default_text(param):
    kind, value = param["kind"], param.get("default")
    if kind == "duration":
        return "%g ms" % value
    if kind == "percent":
        return "%g%%" % (value * 100)
    if kind == "choice":
        labels = {option["value"]: option["label"] for option in param["options"]}
        return labels.get(value, value).split(" – ")[0]
    if kind == "bool":
        return "on" if value else "off"
    if kind == "region":
        return "whole screen"
    if kind in ("point", "image", "recording", "audio", "block", "model"):
        return "none"
    if kind in ("images", "sounds"):
        return "none yet"
    if kind == "audio_device":
        return "the default"
    if kind == "model_settings":
        return "the model's own"
    if kind in ("variable", "definition"):
        return value or "none"
    if kind == "display":
        return "%d (primary)" % (value + 1) if value == 0 else str(value + 1)
    if kind == "text" and value == "":
        return "empty"
    if kind == "hotkey":
        return value or "none"
    if kind == "actions":
        return "one left click"
    if kind == "cases":
        return "one case"
    if kind == "clicker":
        return "left click, 10 per second, until stopped"
    if kind == "code":
        return "a commented starter script"
    if kind in ("int", "float") and param.get("unit"):
        return "%g %s" % (value, param["unit"])
    if kind in ("int", "float"):
        return "%g" % value
    return str(value)


def ports_line(title, ports, with_type):
    if not ports:
        return None
    items = []
    for port in ports:
        label = port["label"] or "(unnamed)"
        if with_type:
            items.append("**%s** (%s)" % (label, TYPE_NAMES[port.get("ty", "any")]))
        else:
            items.append("**%s**" % label)
    return "- %s: %s" % (title, ", ".join(items))


def main():
    # Read and write UTF-8 whatever the console's encoding is.
    definitions = json.load(io.TextIOWrapper(sys.stdin.buffer, encoding="utf-8"))
    out = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", newline="\n")

    out.write("# Block reference\n\n")
    out.write("<!-- Generated by tools/node_docs.py from `macromagi nodes`. Do not edit by hand. -->\n\n")
    out.write("Every block MacroMagi offers, with its ports and settings. **Flow** ports order execution "
              "(top and bottom of a block); **value** ports carry results (left and right).\n\n")
    out.write("The `id` under each heading is the block's type as written in `.magi` files.\n")

    for key, title, blurb in CATEGORIES:
        members = [d for d in definitions if d["category"] == key]
        if not members:
            continue
        out.write("\n## %s\n\n%s\n" % (title, blurb))
        for definition in members:
            out.write("\n### %s\n\n`%s`" % (definition["name"], definition["id"]))
            if definition.get("engines") == "python_only":
                out.write(" · Python engine only")
            out.write("\n\n%s\n\n" % definition["description"])

            lines = []
            if definition.get("flow_in"):
                lines.append("- Flow in: yes")
            flow_out = list(definition.get("flow_out", []))
            if definition.get("dynamic_ports"):
                flow_out.insert(0, {"label": "one per case"})
            flow = ports_line("Flow out", flow_out, with_type=False)
            if flow and any(port["label"] for port in flow_out):
                lines.append(flow)
            elif flow_out:
                lines.append("- Flow out: yes")
            value_in = list(definition.get("data_in", []))
            if definition.get("dynamic_ports"):
                value_in.insert(0, {"label": "one condition per case", "ty": "bool"})
            lines += [line for line in (
                ports_line("Value inputs", value_in, with_type=True),
                ports_line("Value outputs", definition.get("data_out", []), with_type=True),
            ) if line]
            out.write("\n".join(lines) + "\n")

            # Hidden settings are kept for old files, not offered.
            params = [param for param in definition.get("params", []) if not param.get("hidden")]
            if params:
                out.write("\n| Setting | Kind | Default | Notes |\n| --- | --- | --- | --- |\n")
                for param in params:
                    notes = param.get("help", "")
                    if param["kind"] == "choice":
                        options = "; ".join(option["label"] for option in param["options"])
                        notes = (notes + " " if notes else "") + "Options: " + options + "."
                    out.write("| %s | %s | %s | %s |\n" % (
                        param["label"], KIND_NAMES[param["kind"]], default_text(param), notes.replace("|", "\\|")))
    out.flush()


if __name__ == "__main__":
    main()
